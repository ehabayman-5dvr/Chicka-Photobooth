// Sequential memory index tracker for the session (until page reload)
const variationIndices: Record<FlavourType, number> = {
  four_cheese: 0,
  hot_ketchup: 0,
};

let lastActiveFlavour: FlavourType | null = null;

export function getVariationsForFlavour(flavour: FlavourType): VariationConfig[] {
  return flavour === 'four_cheese' ? FOUR_CHEESE_VARIATIONS : HOT_KETCHUP_VARIATIONS;
}

export function getCurrentVariation(flavour: FlavourType): {
  variation: VariationConfig;
  index: number;
  total: number;
} {
  const variations = getVariationsForFlavour(flavour);
  const index = variationIndices[flavour] % variations.length;
  return {
    variation: variations[index],
    index,
    total: variations.length,
  };
}

export function advanceVariation(flavour: FlavourType): void {
  const variations = getVariationsForFlavour(flavour);
  variationIndices[flavour] = (variationIndices[flavour] + 1) % variations.length;
  console.log(
    `[Variation Engine] Advanced ${flavour} to sequential index: ${variationIndices[flavour]} of ${variations.length}`
  );
}

export function setFlavour(flavour: FlavourType): void {
  if (lastActiveFlavour !== null && lastActiveFlavour !== flavour) {
    // Reset index back to 0 when flavour is switched
    variationIndices[flavour] = 0;
    console.log(`[Variation Engine] Switched flavour to ${flavour}. Reset sequential index to 0.`);
  }
  lastActiveFlavour = flavour;
}

export function resetAllVariations(): void {
  variationIndices.four_cheese = 0;
  variationIndices.hot_ketchup = 0;
  console.log('[Variation Engine] Manually reset all variation sequences to 0.');
}

export function getVariationIndices(): Record<FlavourType, number> {
  return { ...variationIndices };
}

